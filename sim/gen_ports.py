#!/usr/bin/env python3
"""Emit ports.svh: a `logic` for every port of the HLS-generated tops, so tb.sv can use `.*`."""
import re
import sys
from pathlib import Path


def ports(verilog: Path):
    text = verilog.read_text()
    raw = dict(re.findall(r"parameter\s+(\w+)\s*=\s*([^;]+);", text))
    params = {}
    for _ in range(5):  # parameters may be defined in terms of other parameters
        for k, expr in raw.items():
            e = expr
            for name, val in sorted(params.items(), key=lambda kv: -len(kv[0])):
                e = re.sub(rf"\b{name}\b", str(val), e)
            try:
                params[k] = int(eval(e.replace("/", "//")))  # noqa: S307
            except Exception:
                pass
    out = {}
    for direction, width, name in re.findall(r"^\s*(input|output)\s+(?:wire\s+|reg\s+)?(\[[^\]]+\])?\s*(\w+)\s*;", text, re.M):
        if width:
            hi, lo = width[1:-1].split(":")
            for k, v in sorted(params.items(), key=lambda kv: -len(kv[0])):
                hi = re.sub(rf"\b{k}\b", str(v), hi)
            w = eval(hi.replace("/", "//")) - int(lo) + 1  # noqa: S307 - integer arithmetic on generated widths
        else:
            w = 1
        out[name] = w
    return out


all_ports = {}
for v in sys.argv[2:]:
    all_ports.update(ports(Path(v)))
lines = [f"logic [{w - 1}:0] {n};" if w > 1 else f"logic {n};" for n, w in all_ports.items()]
Path(sys.argv[1]).write_text("// Generated by gen_ports.py\n" + "\n".join(lines) + "\n")
print(f"{len(lines)} ports -> {sys.argv[1]}")
